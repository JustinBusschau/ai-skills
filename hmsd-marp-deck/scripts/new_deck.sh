#!/usr/bin/env bash
# Start a branded Marp deck, or list the brands that can be applied.
#
# Usage:
#   new_deck.sh --list
#   new_deck.sh <brand-id> <deck.md> [--assets-only | --restyle]
#
# --list prints one line per brand: id, name, description, and meta line (the
# organisation name for title and closing slides), separated by tabs, read
# from the comment at the top of assets/brands/<id>/brand.css.
#
# Otherwise it:
# 1. Copies the brand's logos into brand/<brand-id>/ beside the deck, unless
#    the brand declares "logo: none" in its header (a no-logo brand such as
#    personal, which uses colours and optional decorative images instead).
# 2. Writes <deck.md> with the Marp front matter and one <style> block made of
#    the brand's tokens followed by the shared assets/base.css. Slides are
#    then appended after the header's final comment.
#
# --assets-only copies the logos without touching the deck, for when a deck's
# brand/ folder has gone missing.
#
# --restyle rebrands an existing deck, or refreshes it after base.css or a
# brand changes: it copies the brand's logos and replaces the deck's <style>
# block with a freshly generated one, keeping the deck's --footer-label if
# it was changed from the old brand's default. The slides are left untouched. It refuses (exit 4) a deck whose stylesheet was
# not generated by this script.
#
# It never overwrites a file it did not create: the deck must not already
# exist (except with --restyle, which changes only its <style> block), and an
# existing logo copy is replaced only when it is identical or
# listed in .render-manifest (the same record render.sh keeps).
#
# Adding a brand means adding a folder under assets/brands/ holding brand.css
# (with the same comment header and tokens as the others), logo.svg for light
# backgrounds, and logo-on-dark.svg for brand-coloured ones. For a brand with
# no logo, add "logo: none" to the header and set --logo and --logo-on-dark to
# none; the script then skips both logo files.
#
# Exit codes: 0 done, 2 usage error or unknown brand, 4 refused to overwrite
# (or to restyle a deck it did not start).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
assets="$here/../assets"
brands="$assets/brands"

field() { # field <brand.css> <name>: value of "name:" in the header comment
  sed -n "1,8s/^[[:space:]/*]*$2:[[:space:]]*\(.*[^[:space:]*/]\)[[:space:]*/]*$/\1/p" "$1" | head -1
}

list_brands() {
  local css
  for css in "$brands"/*/brand.css; do
    printf '%s\t%s\t%s\t%s\n' "$(field "$css" brand-id)" "$(field "$css" name)" "$(field "$css" description)" "$(field "$css" meta-line)"
  done
}

usage() { echo "usage: new_deck.sh --list | new_deck.sh <brand-id> <deck.md> [--assets-only | --restyle]" >&2; exit 2; }

[[ $# -ge 1 ]] || usage
if [[ "$1" == "--list" ]]; then list_brands; exit 0; fi
[[ $# -ge 2 && $# -le 3 ]] || usage
brand="$1"; deck="$2"; mode=new
case "${3:-}" in
  "") ;;
  --assets-only) mode=assets ;;
  --restyle) mode=restyle ;;
  *) usage ;;
esac

src="$brands/$brand"
if [[ ! -f "$src/brand.css" ]]; then
  echo "unknown brand: $brand. Available brands:" >&2
  list_brands >&2
  exit 2
fi
no_logo() { [[ "$(field "$src/brand.css" logo)" == "none" ]]; }
brand_files=()
no_logo || brand_files+=(logo.svg logo-on-dark.svg)
extra="$(field "$src/brand.css" extra)"
[[ -n "$extra" ]] && brand_files+=("$extra")
for f in ${brand_files[@]+"${brand_files[@]}"}; do
  [[ -f "$src/$f" ]] || { echo "brand $brand is missing $f" >&2; exit 2; }
done
[[ "$deck" == *.md ]] || { echo "the deck path must end in .md: $deck" >&2; exit 2; }
marker='Generated by new_deck.sh'
if [[ "$mode" == new && -e "$deck" ]]; then
  echo "refusing to overwrite an existing deck: $deck (use --restyle to change its brand)" >&2
  exit 4
fi
if [[ "$mode" == restyle ]]; then
  [[ -f "$deck" ]] || { echo "no deck to restyle: $deck" >&2; exit 2; }
  # Exactly one generated <style> block, so the replacement cannot touch slides.
  if [[ "$(grep -c '^<style>$' "$deck")" != 1 || "$(grep -c '^</style>$' "$deck")" != 1 ]] \
    || ! grep -q "^/\* Brand: .*$marker" "$deck"; then
    echo "refusing to restyle $deck: its stylesheet was not generated by new_deck.sh" >&2
    exit 4
  fi
fi

mkdir -p "$(dirname "$deck")"
deck_dir="$(cd "$(dirname "$deck")" && pwd)"
manifest="$deck_dir/.render-manifest"
# Older versions of this skill used a brand-specific manifest name. Migrate it
# once so existing decks keep their render history without a manual step.
if [[ ! -e "$manifest" && -e "$deck_dir/.hmsd-render-manifest" ]]; then
  mv "$deck_dir/.hmsd-render-manifest" "$manifest"
fi
touch "$manifest"
in_manifest() { grep -Fxq "$1" "$manifest"; }

# Refuse before copying anything if a logo copy would replace someone else's file.
conflicts=()
for f in ${brand_files[@]+"${brand_files[@]}"}; do
  rel="brand/$brand/$f"
  dest="$deck_dir/$rel"
  if [[ -e "$dest" ]] && ! cmp -s "$src/$f" "$dest" && ! in_manifest "$rel"; then
    conflicts+=("$rel")
  fi
done
if (( ${#conflicts[@]} > 0 )); then
  echo "refusing to overwrite files that new_deck.sh did not create:" >&2
  printf '  %s\n' "${conflicts[@]}" >&2
  exit 4
fi

if (( ${#brand_files[@]} == 0 )); then
  echo "no-logo brand: no files copied beside the deck"
else
  mkdir -p "$deck_dir/brand/$brand"
  for f in ${brand_files[@]+"${brand_files[@]}"}; do
    rel="brand/$brand/$f"
    cp "$src/$f" "$deck_dir/$rel"
    in_manifest "$rel" || echo "$rel" >> "$manifest"
  done
  echo "brand assets: $deck_dir/brand/$brand/"
fi

[[ "$mode" == assets ]] && exit 0

# The <style> block's contents: the brand tokens without their header comment,
# then the shared layout. A footer label carried over from a restyled deck
# replaces the brand's default.
stylesheet() {
  printf '/* Brand: %s (%s). %s: do not edit per deck. */\n' "$(field "$src/brand.css" name)" "$brand" "$marker"
  awk -v label="$1" '
    done || /^:root/ {
      done = 1
      if (label != "" && $0 ~ /^[[:space:]]*--footer-label:/) { print "  --footer-label: " label ";"; next }
      print
    }' "$src/brand.css"
  echo
  cat "$assets/base.css"
}

if [[ "$mode" == restyle ]]; then
  label="$(sed -n 's/^[[:space:]]*--footer-label:[[:space:]]*\(.*[^[:space:];]\)[[:space:];]*$/\1/p' "$deck" | head -1)"
  old="$(sed -n "s|^/\* Brand: .*(\(.*\))\. $marker.*|\1|p" "$deck" | head -1)"
  # The old brand's default label is not a choice worth keeping: let the new
  # brand's default apply instead.
  if [[ -n "$label" && -n "$old" && -f "$brands/$old/brand.css" ]]; then
    default="$(sed -n 's/^[[:space:]]*--footer-label:[[:space:]]*\(.*[^[:space:];]\)[[:space:];]*$/\1/p' "$brands/$old/brand.css" | head -1)"
    [[ "$label" == "$default" ]] && label=""
  fi
  tmp="$(mktemp "$deck_dir/.restyle.XXXXXX")"
  css="$(mktemp "$deck_dir/.restyle-css.XXXXXX")"
  trap 'rm -f "$tmp" "$css"' EXIT
  stylesheet "$label" > "$css"
  awk -v css="$css" '
    /^<style>$/ { print; while ((getline line < css) > 0) print line; skip = 1; next }
    /^<\/style>$/ { skip = 0 }
    !skip { print }' "$deck" > "$tmp"
  cat "$tmp" > "$deck"
  echo "restyled: $deck (${old:-unknown} -> $brand, footer label ${label:-from the brand})"
  if [[ -n "$old" && "$old" != "$brand" ]]; then
    echo "check the title and closing slides' meta lines, which may still name the old brand's organisation" >&2
  fi
  exit 0
fi

{
  printf -- '---\nmarp: true\ntheme: default\npaginate: true\nsize: 16:9\n---\n\n<style>\n'
  stylesheet ""
  printf '</style>\n<!-- The first slide goes directly below this line, with no --- before it. -->\n'
} > "$deck"
echo "deck: $deck"
