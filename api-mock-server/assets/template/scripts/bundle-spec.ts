// Bundles a multi-file spec (copied by the scaffold into spec/source/) into the single
// spec/openapi.yaml the mock reads. External $refs are inlined; internal ones are kept.
// Re-run it whenever a file under spec/source/ changes.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { bundle } from '@readme/openapi-parser';
import { stringify } from 'yaml';

const dir = fileURLToPath(new URL('../spec/source/', import.meta.url));
const rootFile = `${dir}.root`;
if (!existsSync(rootFile)) {
  console.log('No spec/source/.root: this project has a single-file spec, so there is nothing to bundle.');
  process.exit(0);
}
const root = `${dir}${readFileSync(rootFile, 'utf8').trim()}`;
const bundled = await bundle(root);
const out = fileURLToPath(new URL('../spec/openapi.yaml', import.meta.url));
writeFileSync(out, `# Generated by npm run bundle:spec from spec/source/. Edit the source files, not this one.\n${stringify(bundled, { aliasDuplicateObjects: false })}`);
console.log(`Bundled ${root} into spec/openapi.yaml`);
