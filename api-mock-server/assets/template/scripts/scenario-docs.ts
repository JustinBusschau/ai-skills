// Writes SCENARIOS.md: the catalogue a client developer reads to find out how to
// reach each outcome. Generated from the registry so it cannot drift from the code.
import { writeFileSync } from 'node:fs';
import { generatedChecks } from '../src/core/checks.ts';
import { config } from '../src/core/config.ts';
import { Contract } from '../src/core/contract.ts';
import { BUILT_INS } from '../src/core/scenarios.ts';
import { domain } from '../src/domain/index.ts';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const contract = await Contract.load(config.specPath, config.basePath);
const lines: string[] = [];
lines.push(`# ${domain.name}: personas and scenarios`, '');
lines.push('Generated by `npm run docs:scenarios`. Do not edit by hand.', '');
lines.push(
  'Send `X-Mock-Session: <your-id>` to work in your own copy of the data, and `POST /__mock/reset` (with `X-Mock-Control-Token`) to restore it. Only scenarios marked "header" can be forced with `X-Mock-Scenario`; reach the others as described.',
  '',
);
lines.push('## Personas', '', '| Persona | What it represents | How to authenticate | Resets on sign-in |', '| --- | --- | --- | --- |');
for (const p of domain.personas) {
  const creds = Object.entries(p.credentials).map(([k, v]) => `${k}: \`${v}\``).join('<br>');
  lines.push(`| \`${p.id}\` | ${esc(p.summary)} | ${creds} | ${p.resetOnSignIn ? 'yes' : 'no'} |`);
}
const byOp = new Map<string, typeof domain.scenarios>();
for (const s of domain.scenarios) byOp.set(s.operationId, [...(byOp.get(s.operationId) ?? []), s]);
lines.push('', '## Scenarios by operation', '');
for (const [op, list] of byOp) {
  lines.push(`### ${op}`, '', '| Status | Error code | Scenario id | Trigger | Outcome | How to trigger |', '| --- | --- | --- | --- | --- | --- |');
  for (const s of [...list].sort((a, b) => a.status - b.status)) {
    lines.push(`| ${s.status} | ${s.errorCode ? `\`${s.errorCode}\`` : ''} | \`${s.id}\` | ${s.trigger} | ${esc(s.summary)} | ${esc(s.how)} |`);
  }
  lines.push('');
}
const checks = generatedChecks(contract, domain);
if (checks.length) {
  lines.push('## Generic responses (every applicable operation)', '', '| Operation | Status | When |', '| --- | --- | --- |');
  for (const c of checks) lines.push(`| ${c.operationId} | ${c.status}${c.documented ? '' : ' (not in the contract)'} | ${esc(c.reason)} |`);
  lines.push('');
}
lines.push('## Built-in scenarios (every operation)', '', '| Id | Effect |', '| --- | --- |');
for (const b of BUILT_INS) lines.push(`| \`${b.id}\` | ${esc(b.summary)} |`);
lines.push('');
writeFileSync(new URL('../SCENARIOS.md', import.meta.url), lines.join('\n'));
console.log('Wrote SCENARIOS.md');
